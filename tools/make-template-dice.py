def dot(a, b): return sum(x * y for x, y in zip(a, b))
def sub(a, b): return tuple(x - y for x, y in zip(a, b))
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def solve(planes):
    (n1, d1), (n2, d2), (n3, d3) = planes
    det = dot(n1, cross(n2, n3))
    if abs(det) < EPS: return None
    p = tuple((d1 * a + d2 * b + d3 * c) / det for a, b, c in zip(cross(n2, n3), cross(n3, n1), cross(n1, n2)))
    return p


def corners(faces):
    planes = [(n, d) for n, d, _, _ in faces]
    found = []
    for trio in itertools.combinations(range(len(planes)), 3):
        p = solve([planes[i] for i in trio])
        if p is None or any(dot(n, p) > d + 1e-5 for n, d in planes): continue
        if not any(math.dist(p, q) < 1e-5 for q in found): found.append(p)
    return found


def polygon(points, normal):
    c = tuple(sum(p[i] for p in points) / len(points) for i in range(3))
    u = sub(points[0], c)
    w = cross(normal, u)
    return sorted(points, key=lambda p: math.atan2(dot(sub(p, c), w), dot(sub(p, c), u)))


def mesh(faces):
    pts = corners(faces)
    v, vt, vn, f, ups = [], [], [], [], []
    for n, d, cu, cv in faces:
        ring = polygon([p for p in pts if abs(dot(n, p) - d) < 1e-5], n)
        base = len(v)
        for p in ring:
            v.append(f"v {p[0]:.6f} {p[1]:.6f} {p[2]:.6f}")
            vt.append(f"vt {dot(cu[:3], p) + cu[3]:.6f} {dot(cv[:3], p) + cv[3]:.6f}")
            vn.append(f"vn {n[0]:.6f} {n[1]:.6f} {n[2]:.6f}")
        f.append("f " + " ".join(f"{base + i + 1}/{base + i + 1}/{base + i + 1}" for i in range(len(ring))))
        ups.append([round(x, 6) for x in n])
    size = [round(max(p[i] for p in pts) - min(p[i] for p in pts), 4) for i in range(3)]
    return "\n".join(v + vt + vn + f) + "\n", ups, size


def main():
    os.makedirs(OUT, exist_ok=True)
    index = {}
    for name, faces in LAYOUT.items():
        obj, ups, size = mesh(faces)
        with open(os.path.join(OUT, f"{name}.obj"), "w", encoding="utf-8", newline="\n") as fh: fh.write(obj)
        index[name] = {"faces": ups, "size": size}
        print(f"{name}: {len(ups)} faces, {size}")
    with open(os.path.join(OUT, "dice.json"), "w", encoding="utf-8", newline="\n") as fh: json.dump(index, fh, indent=1)


main()
